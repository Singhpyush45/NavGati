import { useState } from 'react';
import type { GeminiRequest } from '@/services/ai/geminiHandler';
import { askGemini } from '@/services/ai/gemini';

/** "Ask Gemini" block: one button, optional Hindi/English toggle, the answer and clear AI labelling. */
export function GeminiPanel({ buildRequest, cta, withLanguage = false, note }: {
  buildRequest: (language: 'en' | 'hi') => GeminiRequest; cta: string; withLanguage?: boolean; note?: string;
}) {
  const [lang, setLang] = useState<'en' | 'hi'>('en');
  const [busy, setBusy] = useState(false);
  const [out, setOut] = useState<{ text: string; model: string } | null>(null);
  const [err, setErr] = useState<string | null>(null);

  const run = async () => {
    setBusy(true); setErr(null);
    try { setOut(await askGemini(buildRequest(lang))); } catch (e) { setErr((e as Error).message); } finally { setBusy(false); }
  };

  return (
    <div className="rounded-xl border border-violet/30 bg-gradient-to-br from-violet/10 to-tide/5 p-4">
      <div className="flex flex-wrap items-center gap-3">
        <button type="button" className="btn-primary !py-2" onClick={run} disabled={busy}>
          ✨ {busy ? 'Gemini is thinking…' : out ? 'Regenerate' : cta}
        </button>
        {withLanguage && (
          <div className="flex gap-1 text-xs" role="radiogroup" aria-label="Language">
            {(['en', 'hi'] as const).map((l) => (
              <button key={l} type="button" role="radio" aria-checked={lang === l} onClick={() => setLang(l)}
                className={`rounded-full border px-3 py-1 ${lang === l ? 'border-tide bg-tideSoft text-tide' : 'border-line text-muted'}`}>{l === 'en' ? 'English' : 'हिंदी'}</button>
            ))}
          </div>
        )}
        {note && <span className="text-xs text-muted">{note}</span>}
      </div>
      {busy && <div className="mt-3 h-16 animate-pulse rounded-lg bg-sunken/70" />}
      {out && !busy && (
        <div className="mt-3">
          <p className="whitespace-pre-wrap text-sm leading-relaxed">{out.text}</p>
          <p className="mt-2 text-[11px] text-muted">Generated by Google {out.model} from anonymised measurements · AI-generated, may be wrong · not medical advice.</p>
        </div>
      )}
      {err && <p className="mt-3 text-sm text-alert">{err}</p>}
    </div>
  );
}
